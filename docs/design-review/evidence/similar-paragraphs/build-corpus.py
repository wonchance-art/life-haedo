def export(name, documents):
    data = {
        "schemaVersion": 1,
        "set": name,
        "note": "합성·익명 한국어 자료. 실제 사람·계정·기사가 아니며 연구·통계 서술도 가상이다.",
        "documents": [
            {"id": doc_id, "kind": kind, "title": title, "text": "\n\n".join(paragraphs)}
            for doc_id, kind, title, paragraphs in documents
        ],
    }
    path = HERE / f"{name}-corpus.json"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path, sum(len(p) for *_, p in documents)


